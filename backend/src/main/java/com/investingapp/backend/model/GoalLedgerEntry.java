package com.investingapp.backend.model;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.investingapp.backend.util.EasternTime;
import jakarta.persistence.*;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * One line of a goal unit's "Saved so far" tally: a payday credit or a correction. The unit key is
 * {@code "goal"} for simple and vacation goals, or {@code "kid:<index>:<account>"} for kids.
 */
@Data
@NoArgsConstructor
@Entity
@Table(name = "goal_ledger_entries")
public class GoalLedgerEntry {

    public enum LedgerKind { CREDIT, MISSED, EXTRA, SET }

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "goal_id", nullable = false)
    @JsonIgnore
    private Goal goal;

    @Column(length = 40, nullable = false)
    private String unit;

    @Column(name = "entry_date", nullable = false)
    private LocalDate entryDate;

    @Enumerated(EnumType.STRING)
    @Column(length = 8, nullable = false)
    private LedgerKind kind;

    @Column(precision = 12, scale = 2, nullable = false)
    private BigDecimal amount;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /** Generated by the database: makes a CREDIT unique per unit and day. Never written from here. */
    @Column(name = "credit_key", insertable = false, updatable = false)
    @JsonIgnore
    private String creditKey;

    @PrePersist
    void onCreate() {
        createdAt = EasternTime.now();
    }
}
