-- Makes room for an encrypted Social Security Number on a beneficiary.
--
-- The column was varchar(11), exactly one "123-45-6789". It now holds AES-GCM ciphertext
-- ("ENC:" plus base64, about 56 characters), written by EncryptedStringConverter. Rows written
-- before this are left as they are: there is no production database yet, and the dev and local
-- profiles can still read a plain-text value.
--
-- Why a repeatable migration and not the next V number: another branch already holds V12 and has
-- not been pushed. Any V number chosen here would land out of order on one database or another,
-- and Flyway refuses to start when that happens. A repeatable migration runs after the versioned
-- ones on every database, whatever version it is at.
--
-- It only acts when the column exists and is still a varchar narrower than 255, so running it
-- again does nothing, and a later versioned migration is free to widen, retype, rename or drop
-- the column without this file undoing or tripping over it. Do not edit this file once it has
-- shipped (an edit makes it run again everywhere).

SET @stmt := (SELECT IF(COUNT(*) = 1,
        'ALTER TABLE beneficiaries MODIFY social_security_number VARCHAR(255) NOT NULL',
        'DO 0')
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'beneficiaries'
      AND COLUMN_NAME = 'social_security_number'
      AND DATA_TYPE = 'varchar' AND CHARACTER_MAXIMUM_LENGTH < 255);
PREPARE widen_column FROM @stmt;
EXECUTE widen_column;
DEALLOCATE PREPARE widen_column;
