-- adopted (develop @ 1c9c44c). From here on the entities follow the migrations, not the other way
-- around: ddl-auto is `validate` in every profile.
--
-- Tables are emitted alphabetically, so foreign keys are created against tables that may not exist
-- yet; checks are disabled for the length of this script and restored at the end.
--
-- Existing databases (local, Railway dev) are stamped with `flyway baseline` at version 1 instead
-- of running this script. See FREDdocs/flyway-baseline.md.

